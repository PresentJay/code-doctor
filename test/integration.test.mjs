test('doctor identifies a retained writer lock and never removes it automatically', async t=>{
  const root = await fixture(t);
  await mkdir(path.join(root,'.code-doctor/write.lock'),{recursive:true});
  await writeFile(path.join(root,'.code-doctor/write.lock/owner.json'),'');
  const starting = run(root,'capture'); assert.match(starting.stderr,/busy/);
  assert.equal(JSON.parse(run(root,'doctor').stdout).storage.lock.pid,null);
  await writeFile(path.join(root,'.code-doctor/write.lock/owner.json'),JSON.stringify({pid:process.pid,createdAt:'2026-10-22T00:00:00.000Z'}));
  const capture = run(root,'capture');
  assert.notEqual(capture.status,0); assert.match(capture.stderr,new RegExp(`owner PID ${process.pid}`));
  const doctor = run(root,'doctor'); assert.equal(doctor.status,0,doctor.stderr);
  assert.equal(JSON.parse(doctor.stdout).storage.lock.pid,process.pid);
  assert.ok(await readFile(path.join(root,'.code-doctor/write.lock/owner.json')));
  await rm(path.join(root,'.code-doctor/write.lock'),{recursive:true});
  const recovered = run(root,'capture'); assert.equal(recovered.status,0,recovered.stderr);
});

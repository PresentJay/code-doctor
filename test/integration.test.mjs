test('outline CLI/MCP reads preserve every unit and original identity without patches or storage writes', {timeout:30000}, async t=>{
  const root = await fixture(t);
  const base = git(root,'rev-parse','HEAD').toString().trim();
  git(root,'mv','a.js','renamed.js');
  await writeFile(path.join(root,'empty.txt'),'');
  await writeFile(path.join(root,'binary.dat'),Buffer.from([0,1,2,3]));
  await writeFile(path.join(root,'long.js'),'export const additional = true;\n'.repeat(120));
  const service = await createService(root);
  const original = await service.capture({base,task:'이름과 값 변경을 검토한다.',kind:'change',context:{requirements:['모든 변경을 읽는다.'],references:[{title:'요구',source:'issue:fixture',revision:'1'}]}});
  const planned = await service.plan({reviewId:original.id,summary:'중요한 변경부터 읽습니다.',blocks:[...original.blocks].reverse().map(block=>({...block,importance:'high',relation:'requested'}))});
  await service.feedback({reviewId:planned.id,blockId:planned.blocks[0].id,text:'검증용 의견'});
  const folder = path.join(root,'.code-doctor');
  const snapshot = async()=>Promise.all((await readdir(folder,{recursive:true})).filter(file=>file.endsWith('.json')).sort().map(async file=>[file,await readFile(path.join(folder,file),'utf8')]));
  const before = await snapshot();
  const client = new Client({name:'outline-test',version:'1.0.0'});
  t.after(()=>client.close());
  await client.connect(new StdioClientTransport({command:process.execPath,args:[entry,'mcp','--repo',root],stderr:'pipe'}));
  const outline = data(await client.callTool({name:'read_review',arguments:{view:'outline'}}));
  assert.deepEqual(JSON.parse(run(root,'read','--view','outline').stdout),outline);
  assert.equal(outline.view,'outline'); assert.equal(outline.id,planned.id); assert.equal(outline.latestReviewId,planned.id);
  assert.equal(outline.freshness.state,'current');
  assert.deepEqual(outline.units,planned.units.map(({patch,...unit})=>unit));
  assert.ok(outline.units.some(unit=>unit.binary)); assert.ok(outline.units.some(unit=>unit.file==='empty.txt'));
  assert.ok(outline.units.some(unit=>unit.previousFile==='a.js')); assert.ok(outline.units.some(unit=>unit.stage==='index')); assert.ok(outline.units.some(unit=>unit.stage==='worktree'));
  assert.deepEqual(outline.blocks,planned.blocks); assert.deepEqual(outline.task,planned.task);
  for (const key of ['repoRoot','base','baseCommit','headCommit','fingerprint']) assert.equal(outline[key],planned[key]);
  assert.equal(outline.sourceStats.unitCount,planned.units.length); assert.ok(outline.sourceStats.fullPatchLines>120);
  assert.ok(Buffer.byteLength(JSON.stringify(outline))<Buffer.byteLength(JSON.stringify(planned)));
  assert.deepEqual(data(await client.callTool({name:'read_review',arguments:{}})),planned);
  assert.deepEqual(JSON.parse(run(root,'read').stdout),planned);
  assert.deepEqual(JSON.parse(run(root,'read','--view','full').stdout),planned);
  const fullBlock = data(await client.callTool({name:'read_block',arguments:{blockId:planned.blocks[0].id,view:'full'}}));
  assert.deepEqual(fullBlock.units,planned.blocks[0].unitIds.map(id=>planned.units.find(unit=>unit.id===id)));
  const oldPlan = data(await client.callTool({name:'read_review',arguments:{reviewId:original.id,view:'outline'}}));
  assert.equal(oldPlan.id,original.id); assert.equal(oldPlan.latestReviewId,planned.id); assert.equal(oldPlan.freshness.state,'current');
  assert.deepEqual(oldPlan.blocks,original.blocks);
  assert.deepEqual(await snapshot(),before);
  assert.equal((await client.callTool({name:'read_review',arguments:{view:'focus'}})).isError,true);
  const invalid = run(root,'read','--view','focus'); assert.notEqual(invalid.status,0); assert.match(invalid.stderr,/full or outline/);
  assert.equal((await client.callTool({name:'read_review',arguments:{reviewId:'review-000000000000000000000000',view:'outline'}})).isError,true);
  const raw = await readFile(path.join(folder,'review.json'),'utf8');
  await writeFile(path.join(folder,'review.json'),JSON.stringify({...planned,units:planned.units.map((unit,i)=>i ? unit : {...unit,patch:unit.patch+'tampered'})}));
  assert.equal((await client.callTool({name:'read_review',arguments:{view:'outline'}})).isError,true,'outline must validate original patches before projecting');
  await writeFile(path.join(folder,'review.json'),raw);
  await writeFile(path.join(root,'renamed.js'),'export const answer = 3;\n');
  git(root,'add','.'); git(root,'commit','-qm','next source revision');
  const revised = await service.capture();
  const archived = data(await client.callTool({name:'read_review',arguments:{reviewId:planned.id,view:'outline'}}));
  assert.deepEqual({...archived,latestReviewId:outline.latestReviewId,freshness:outline.freshness},outline);
  assert.equal(archived.latestReviewId,revised.id); assert.equal(archived.freshness.state,'changed');
  assert.deepEqual(JSON.parse(run(root,'read','--review',planned.id,'--view','outline').stdout),archived);
  assert.deepEqual(await service.read({reviewId:planned.id}),planned);
});

test('oversized MCP results keep saved source and the same connection usable for outline and focused code', {timeout:30000}, async t=>{
  const root = await fixture(t);
  const line = '// '+ 'x'.repeat(90)+'\n';
  const text = line.repeat(Math.ceil(11 * 1024 * 1024 / line.length));
  await writeFile(path.join(root,'large.js'),text);
  const client = new Client({name:'large-result-test',version:'1.0.0'});
  t.after(()=>client.close());
  const errors = []; client.onerror = error=>errors.push(error.message);
  await client.connect(new StdioClientTransport({command:process.execPath,args:[entry,'mcp','--repo',root],stderr:'pipe'}));
  const captured = await client.callTool({name:'capture_review',arguments:{task:'큰 변경도 누락 없이 읽는다.'}});
  assert.equal(captured.isError,true);
  const error = JSON.parse(captured.content[0].text); assert.match(error.error,/operation completed/); assert.match(error.error,/outline/);
  const service = await createService(root);
  const saved = await service.read(); assert.equal(saved.id,error.reviewId);
  const large = saved.units.find(unit=>unit.file==='large.js'); assert.ok(Buffer.byteLength(large.patch)>Buffer.byteLength(text)); assert.ok(large.patch.includes('+'+line));
  const outline = data(await client.callTool({name:'read_review',arguments:{reviewId:error.reviewId,view:'outline'}}));
  assert.deepEqual(outline.units,saved.units.map(({patch,...unit})=>unit));
  assert.equal((await client.callTool({name:'read_review',arguments:{}})).isError,true);
  assert.equal((await client.callTool({name:'read_review',arguments:{view:'guide'}})).isError,true,'guide without focus must keep the full code and the same size limit');
  const blocks = saved.blocks.map(block=>block.unitIds.includes(large.id) ? {...block,focus:[{unitId:large.id,side:'new',startLine:1,endLine:2}]} : block);
  const planned = await client.callTool({name:'plan_review',arguments:{reviewId:saved.id,summary:'큰 파일은 실제 두 줄부터 읽습니다.',blocks}});
  assert.equal(planned.isError,true); const plannedId = JSON.parse(planned.content[0].text).reviewId;
  const blockId = blocks.find(block=>block.unitIds.includes(large.id)).id;
  const focused = data(await client.callTool({name:'read_block',arguments:{reviewId:plannedId,blockId}}));
  const guide = data(await client.callTool({name:'read_review',arguments:{view:'guide'}}));
  assert.equal(guide.id,plannedId);
  assert.deepEqual(guide.blocks.find(block=>block.id===blockId).excerpts,focused.excerpts);
  assert.equal(focused.view,'focus'); assert.deepEqual(focused.excerpts[0].rows.map(row=>row.text),[line.trimEnd(),line.trimEnd()]);
  assert.equal((await client.callTool({name:'read_block',arguments:{reviewId:plannedId,blockId,view:'full'}})).isError,true);
  assert.ok((await client.listTools()).tools.some(tool=>tool.name==='read_review')); assert.deepEqual(errors,[]);
  assert.equal((await service.read()).id,plannedId); assert.equal((await service.read()).units.find(unit=>unit.id===large.id).patch,large.patch);
});

